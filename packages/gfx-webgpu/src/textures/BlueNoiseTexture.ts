/**
 * Create a blue noise texture from precomputed data.
 *
 * @param device - GPU device to create texture on
 * @param size - Texture size (default 64, must match precomputed data)
 * @returns GPU texture containing blue noise pattern
 */
export function createBlueNoiseTexture(device: GPUDevice, size = 64): GPUTexture {
  // Verify size matches precomputed data
  if (size !== 64) {
    console.warn(
      `[BlueNoiseTexture] Requested size ${size} but precomputed data is 64x64. Using 64x64.`
    );
    size = 64;
  }

  // Convert grayscale to RGBA
  const pixelCount = size * size;
  const data = new Uint8Array(pixelCount * 4);

  for (let i = 0; i < pixelCount; i++) {
    const val = BLUE_NOISE_64x64[i]!;
    const pixelIdx = i * 4;
    data[pixelIdx] = val; // R
    data[pixelIdx + 1] = val; // G
    data[pixelIdx + 2] = val; // B
    data[pixelIdx + 3] = 255; // A (fully opaque)
  }

  // Create texture
  const texture = device.createTexture({
    label: 'Blue Noise Texture (Precomputed)',
    size: [size, size, 1],
    format: 'rgba8unorm',
    usage: GPUTextureUsage.TEXTURE_BINDING | GPUTextureUsage.COPY_DST,
  });

  // Upload data
  device.queue.writeTexture({ texture }, data, { bytesPerRow: size * 4 }, { width: size, height: size });

  return texture;
}

/**
 * Generates blue noise texture at runtime using void-and-cluster algorithm.
 * This is slower than using precomputed data but produces high-quality results.
 *
 * Use this if you need a different size than the precomputed 64x64,
 * or want to generate fresh patterns for testing.
 *
 * @param device - GPU device to create texture on
 * @param size - Texture size (power of 2 recommended, max 256)
 * @returns GPU texture containing blue noise pattern
 */
export function generateBlueNoiseTexture(device: GPUDevice, size = 64): GPUTexture {
  // Clamp size to reasonable limits
  size = Math.min(Math.max(size, 16), 256);

  const pixelCount = size * size;
  const data = new Uint8Array(pixelCount * 4);

  // Void-and-Cluster algorithm implementation
  // This produces true blue noise with proper spectral properties
  const ranks = voidAndCluster(size);

  // Normalize ranks to 0-255 and fill RGBA data
  const maxRank = pixelCount - 1;
  for (let i = 0; i < pixelCount; i++) {
    const val = Math.round((ranks[i]! / maxRank) * 255);
    const pixelIdx = i * 4;
    data[pixelIdx] = val; // R
    data[pixelIdx + 1] = val; // G
    data[pixelIdx + 2] = val; // B
    data[pixelIdx + 3] = 255; // A
  }

  // Create texture
  const texture = device.createTexture({
    label: `Blue Noise Texture (Generated ${size}x${size})`,
    size: [size, size, 1],
    format: 'rgba8unorm',
    usage: GPUTextureUsage.TEXTURE_BINDING | GPUTextureUsage.COPY_DST,
  });

  // Upload data
  device.queue.writeTexture({ texture }, data, { bytesPerRow: size * 4 }, { width: size, height: size });

  return texture;
}

/**
 * Void-and-Cluster algorithm for generating blue noise.
 * Based on Ulichney's void-and-cluster method.
 *
 * @param size - Texture dimension (assumed square)
 * @returns Array of rank values for each pixel
 */
function voidAndCluster(size: number): Uint16Array {
  const pixelCount = size * size;
  const ranks = new Uint16Array(pixelCount);
  const binary = new Uint8Array(pixelCount); // 0 = void (minority), 1 = cluster (majority)

  // Gaussian filter sigma (determines energy distribution)
  const sigma = 1.5;
  const filterRadius = Math.ceil(sigma * 2.5);

  // Energy calculation with toroidal wrapping
  const calculateEnergy = (x: number, y: number): number => {
    let energy = 0;
    for (let dy = -filterRadius; dy <= filterRadius; dy++) {
      for (let dx = -filterRadius; dx <= filterRadius; dx++) {
        if (dx === 0 && dy === 0) continue;
        const nx = (x + dx + size) % size;
        const ny = (y + dy + size) % size;
        if (binary[ny * size + nx]) {
          const dist2 = dx * dx + dy * dy;
          energy += Math.exp(-dist2 / (2 * sigma * sigma));
        }
      }
    }
    return energy;
  };

  // Phase 1: Initial binary pattern (seeded with ~10% points)
  const initialPoints = Math.floor(pixelCount * 0.1);
  let placed = 0;

  // Place initial points using simple random with rejection
  const rng = mulberry32(12345); // Deterministic seed for reproducibility
  while (placed < initialPoints) {
    const idx = Math.floor(rng() * pixelCount);
    if (!binary[idx]) {
      binary[idx] = 1;
      placed++;
    }
  }

  // Phase 2: Remove tightest cluster point, place in largest void
  // Continue until half the pixels are filled
  const halfCount = pixelCount >> 1;
  let rank = halfCount - 1;

  while (placed > 0) {
    // Find tightest cluster (highest energy among 1s)
    let maxEnergy = -Infinity;
    let tightestIdx = 0;
    for (let y = 0; y < size; y++) {
      for (let x = 0; x < size; x++) {
        const idx = y * size + x;
        if (binary[idx]) {
          const energy = calculateEnergy(x, y);
          if (energy > maxEnergy) {
            maxEnergy = energy;
            tightestIdx = idx;
          }
        }
      }
    }

    // Remove tightest cluster point and assign rank
    binary[tightestIdx] = 0;
    ranks[tightestIdx] = rank--;
    placed--;
  }

  // Phase 3: Fill remaining voids
  // Start fresh with the ranked pixels as seeds
  for (let i = 0; i < pixelCount; i++) {
    if (ranks[i]! > 0) {
      binary[i] = 1;
      placed++;
    }
  }

  rank = halfCount;
  while (placed < pixelCount) {
    // Find largest void (lowest energy among 0s)
    let minEnergy = Infinity;
    let voidIdx = 0;
    for (let y = 0; y < size; y++) {
      for (let x = 0; x < size; x++) {
        const idx = y * size + x;
        if (!binary[idx]) {
          const energy = calculateEnergy(x, y);
          if (energy < minEnergy) {
            minEnergy = energy;
            voidIdx = idx;
          }
        }
      }
    }

    // Fill void and assign rank
    binary[voidIdx] = 1;
    ranks[voidIdx] = rank++;
    placed++;
  }

  return ranks;
}

/**
 * Simple seeded random number generator (Mulberry32)
 */
function mulberry32(seed: number): () => number {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
